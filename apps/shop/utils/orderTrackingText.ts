export const shopOrderHasCheckboxProjection = (order: { fiscal_status?: string, receipt_delivery_status?: string }) => checkboxProjectionStates.some(state => state === order.fiscal_status || state === order.receipt_delivery_status)

// Explicit NP return projections are separate from payment evidence and legacy test-carrier states.
export const npReturnProjectionStates = ["np_return_pending", "np_return_received", "np_return_fiscalized", "np_refusal_closed", "simulated_np_return_pending", "simulated_np_return_received", "simulated_np_return_fiscalized", "simulated_np_refusal_closed"] as const
export const shopOrderHasNPReturnProjection = (order: { fulfillment_status?: string }) => npReturnProjectionStates.some(state => state === order.fulfillment_status)

// Exact R4 canonical projections; provider authority is never inferred as test.
export const paymentResolutionProjectionStates = ["refunded", "financial_exception", "cancelled_before_handover", "cancellation_pending", "simulated_refunded", "simulated_financial_exception", "simulated_cancelled_before_handover", "simulated_cancellation_pending"] as const
export const shopOrderHasPaymentResolutionProjection = (order: { payment_status?: string, fulfillment_status?: string }) => paymentResolutionProjectionStates.some(state => state === order.payment_status || state === order.fulfillment_status)

// Only canonical paid projections mount payment facts before a fiscal document exists.
