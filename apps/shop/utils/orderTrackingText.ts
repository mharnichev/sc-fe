// Explicit canonical test facts warrant their projection even when no fiscal document exists.
export const shopOrderHasTestProjection = (order: { fiscal_status?: string, fulfillment_status?: string }) => !!order.fiscal_status?.startsWith('simulated_fiscal_') || ['simulated_carrier_return_unknown', 'simulated_carrier_returning', 'simulated_carrier_returned', 'simulated_carrier_return_received', 'simulated_unpaid_refusal_closed'].includes(order.fulfillment_status || '')

