import { expect, test } from '@playwright/test'

for (const width of [390, 768, 1024, 1440]) {
  test(`header search stays accessible at ${width}px @mobile`, async ({ page, baseURL }) => {
    const origin = new URL(baseURL!).origin
    await page.setViewportSize({ width, height: 900 })
    await page.route('**/*', async route => {
      const url = new URL(route.request().url())
      if (['localhost', '127.0.0.1'].includes(url.hostname) && url.pathname.includes('/api/v1/')) {
        await route.fulfill({ json: { items: [], total: 0, suggestions: ['synthetic result'], products: [], categories: [] } })
      } else if (url.origin !== origin) await route.abort()
      else await route.continue()
    })
    await page.goto('contacts')
    if (width < 768) {
      const trigger = page.locator('.shop-header__mobile-btn').first()
      await trigger.click()
      const panel = page.locator('#shop-mobile-search')
      const input = panel.getByRole('searchbox')
      await expect(panel).toBeVisible()
      await expect(input).toBeFocused()
      await expect(trigger).toHaveAttribute('aria-expanded', 'true')
      await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
      await page.locator('.shop-header__mobile-logo').focus()
      await expect(input).toBeFocused()
      await page.keyboard.press('Tab')
      await expect.poll(() => panel.evaluate(element => element.contains(document.activeElement))).toBe(true)
      await trigger.click()
      await expect(panel).not.toBeVisible()
      await expect(trigger).toBeFocused()
      await trigger.click()
      await expect(input).toBeFocused()
      await page.locator('.full-page-dim-background').dispatchEvent('click')
      await expect(panel).not.toBeVisible()
      await expect(trigger).toBeFocused()
      await trigger.click()
      await input.fill('synthetic')
      await expect(panel.locator('.header-search__panel')).toBeVisible()
      const close = panel.locator('.shop-header__search-panel-heading button')
      await close.focus()
      await page.keyboard.press('Shift+Tab')
      await expect(panel.locator('button:visible').last()).toBeFocused()
      await page.keyboard.press('Escape')
      await expect(trigger).toBeFocused()
      await expect(trigger).toHaveAttribute('aria-expanded', 'false')
      await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
      await trigger.click()
      await page.setViewportSize({ width: 768, height: 900 })
      await expect(panel).not.toBeVisible()
      await expect(page.locator('.shop-header__soulcuts')).toBeFocused()
      await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
      await page.setViewportSize({ width: 390, height: 900 })
      await trigger.click()
      await page.evaluate(async () => {
        const app = (document.querySelector('#__nuxt') as HTMLElement & { __vue_app__: { config: { globalProperties: { $router: { push: (path: string) => Promise<unknown> } } } } }).__vue_app__
        await app.config.globalProperties.$router.push('/brands')
      })
      await expect(panel).not.toBeVisible()
      await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
      await trigger.click()
      await page.locator('.shop-header__mobile-btn').nth(1).click()
      await expect(panel).not.toBeVisible()
      await expect(page.locator('.base-modal[role=dialog]')).toBeVisible()
      await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
      await page.locator('.base-modal__close').click()
      await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
    } else {
      const input = page.locator('.shop-header__desktop').getByRole('searchbox')
      await input.fill('synthetic')
      await expect(page.locator('.header-search__panel--desktop')).toBeVisible()
      await input.press('Escape')
      await expect(page.locator('.header-search__panel--desktop')).not.toBeVisible()
      await expect(input).toBeFocused()
    }
  })
}
